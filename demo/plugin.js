/**
 * Colourunder — browser demo.
 *
 * VHS's helical-scan colour-under recording. A VHS deck cannot record colour
 * at its broadcast frequency, so it heterodynes the chroma down under the
 * luma's FM carrier and back up on playback: chroma keeps about 40 lines of
 * resolution, arrives late, picks up band-limited blotches of noise, and its
 * playback phase error is a hue shift on NTSC and a desaturation on PAL. The
 * two heads on the spinning drum add the rest: the switch 6.5 lines before V
 * sync tears the bottom lines sideways, a tracking error walks a noise bar up
 * the picture, and missing oxide drops a line to white or, with DOC on, to a
 * repeat of the line 1H above.
 *
 * Like receipt and instant, this plugin is **not only a shader**, and the two
 * halves of the page are not equally faithful:
 *
 *   The shaders are the plugin's. The version line, the `kCommon` block and
 *   the eight bodies of `source/Shaders.cpp` (vertex, intakev, intakeh, noise,
 *   tape, comb, doc, display) are spliced into the generated block below by
 *   `demo/tools/sync_shaders.py`, tabs and comments included, and `assemble`
 *   below is Shaders.cpp's. `demo/tools/check_shaders.py --dump` compares
 *   every assembled stage with what the plugin compiles
 *   (`cutest --dump-shaders`); `tools/verify.sh` runs it.
 *
 *   The CPU half is a PORT. In the plugin every coefficient -- the nine
 *   kernels, the per-line tracking bar, noise gain and phase error (its cos
 *   and sin in double), the head switch and the AFC's recovery, the dropouts,
 *   the noise seeds, the clock -- is computed once a frame in C++ and handed
 *   over as uniforms and one RGBA32F texture. `demo/model.js` is a hand
 *   translation of that, and `demo/tools/check_port.sh` compares it with the
 *   plugin's own ProcessOpenGL and constructor, run under a recorder, value
 *   for value. This file's GL half (which WebGL object each name in the plan
 *   is, and the draws) only a reader checks.
 *
 * ------------------------------------------------------ the frame
 *
 *   plan      model.js: the settings, the clock, the kernels, LineData and
 *             every pass's uniforms (CPU, in double, floats where the plugin
 *             hands floats over)
 *   upload    LineData, N x 6 RGBA32F
 *   intakev   host rows onto the standard's 576 or 480 lines (N x W)
 *   intakeh   pixels onto the line raster's Ws samples (N x Ws)
 *   per generation, 1..5:
 *     noise   seeded white noise
 *     tape    the filters, the FM and chroma noise, the bar, the switching
 *             transient, the phase error, the dropouts
 *     comb    the 1H chroma average
 *     doc     the dropout compensator
 *   display   nearest line per row, Catmull-Rom across, the time-base
 *             displacement, Y'UV to R'G'B', Mix
 */

