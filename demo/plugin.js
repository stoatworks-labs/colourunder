function declarationToKit(d, id) {
  const extra = HINTS[id] ?? {};
  const base = { id, name: d.name, group: d.group, hint: extra.hint };
  if (d.type === 'option') return { ...base, type: 'option', elements: d.elements, default: Math.round(d.default) };
  if (d.type === 'integer') return { ...base, type: 'option', elements: GENERATIONS, default: generationIndex(Math.round(d.default)) };
  if (d.type === 'boolean') return { ...base, type: 'boolean', default: d.default };
  return { ...base, type: 'standard', default: d.default, display: extra.display };
}

