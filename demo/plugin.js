/// What the line under the canvas reports. Filled by the renderer.
const telemetry = {
  ticked: false, seconds: 0, frame: 0, standard: 0, speed: 1, generations: 1, tracking: 0,
  N: 0, Ws: 0, k: 1, drops: 0, switchLine: 0, missing: [], uniformVectors: 0,
};

/// For a driven check (AGENTS.md, "The browser demo"). `fresh()` puts the
/// renderer back to a newly instantiated plugin; `afterRender(gl, input)` runs
/// inside the frame, before the canvas is composited, so it can read it back.
const hooks = { afterRender: null, fresh: null };

function createRenderer(gl, quad) {
  telemetry.uniformVectors = gl.getParameter(gl.MAX_FRAGMENT_UNIFORM_VECTORS);

  // InitGL: every stage, as Shaders.cpp assembles it.
  const vertex = assemble(VERTEX_BODY, STAGE_COMMON.VERTEX_BODY);
  const programs = {};
  const stages = [
    ['intakev', 'INTAKEV_BODY', INTAKEV_BODY], ['intakeh', 'INTAKEH_BODY', INTAKEH_BODY],
    ['noise', 'NOISE_BODY', NOISE_BODY], ['tape', 'TAPE_BODY', TAPE_BODY],
    ['comb', 'COMB_BODY', COMB_BODY], ['doc', 'DOC_BODY', DOC_BODY], ['display', 'DISPLAY_BODY', DISPLAY_BODY],
  ];
  for (const [name, key, body] of stages) {
    try {
      programs[name] = new Program(gl, vertex, assemble(body, STAGE_COMMON[key]), name);
    } catch (error) {
      if (name === 'tape') {
        throw new GLError(`${error.message}\n\nThe tape pass declares four 96-float uniform arrays (its kernels) and 24 dropouts, about 410 fragment uniform vectors; this browser offers ${telemetry.uniformVectors}. WebGL2 only promises 224, so on this device the plugin's tape shader cannot be compiled as written, and the page will not substitute a smaller one.`);
      }
      throw error;
    }
  }

  // The plugin's buffers: RGBA32F, nearest (every read is texelFetch).
  const nearest = { filter: 'nearest' };
  const buffers = {
    columns: new PassBuffer(gl, nearest),
    intake: new PassBuffer(gl, nearest),
    work0: new PassBuffer(gl, nearest),
    work1: new PassBuffer(gl, nearest),
    work2: new PassBuffer(gl, nearest),
    noise: new PassBuffer(gl, nearest),
  };
  let lineData = null;

  let instance = new Instance();
  hooks.fresh = () => { instance = new Instance(); };

  const parameterFloats = (params) => {
    const p = new Array(10).fill(0);
    p[PT.STANDARD] = params.get('standard');
    p[PT.SPEED] = params.get('speed');
    p[PT.TRACKING] = params.get('tracking');
    p[PT.HEAD_SWITCH] = params.get('headSwitch');
    p[PT.WEAR] = params.get('wear');
    p[PT.GENERATION] = generationValue(params.get('generation'));
    p[PT.DOC] = params.get('doc');
    p[PT.CHROMA_DELAY] = params.get('chromaDelay');
    p[PT.CHROMA_NOISE] = params.get('chromaNoise');
    p[PT.MIX] = params.get('mix');
    return p.map(Math.fround);
  };

  return {
    render({ input, params, width, height, time }) {
      const W = width;
      const H = height;

      // Colourunder::SetTime, then the CPU half (model.js).
      instance.setTime(time);
      const plan = instance.planFrame(parameterFloats(params), W, H);
      const R = plan.raster;

      // Buffers, before anything is bound (PassBuffer::Ensure).
      buffers.columns.ensure(W, R.N, gl.RGBA32F);
      for (const name of ['intake', 'work0', 'work1', 'work2', 'noise']) buffers[name].ensure(R.Ws, R.N, gl.RGBA32F);
      if (plan.allocate || lineData === null) {
        if (lineData !== null) gl.deleteTexture(lineData);
        lineData = gl.createTexture();
        gl.bindTexture(gl.TEXTURE_2D, lineData);
        gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA32F, R.N, plan.dataRows, 0, gl.RGBA, gl.FLOAT, null);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
      }
      gl.bindTexture(gl.TEXTURE_2D, lineData);
      gl.pixelStorei(gl.UNPACK_ALIGNMENT, 4);
      gl.texSubImage2D(gl.TEXTURE_2D, 0, 0, 0, R.N, plan.dataRows, gl.RGBA, gl.FLOAT, plan.lineData);
      gl.bindTexture(gl.TEXTURE_2D, null);

      const textureOf = (name) => {
        if (name === 'picture') return input.texture;
        if (name === 'lineData') return lineData;
        return buffers[name].texture;
      };

      gl.disable(gl.BLEND);
      let drops = 0;
      for (const pass of plan.passes) {
        if (pass.target === 'host') {
          gl.bindFramebuffer(gl.FRAMEBUFFER, null);
          gl.viewport(0, 0, W, H);
        } else {
          buffers[pass.target].bind();
        }
        const prog = programs[pass.name].use();
        for (const [k, v] of Object.entries(pass.ints)) prog.setInt(k, v);
        for (const [k, v] of Object.entries(pass.uints)) prog.setUint(k, v);
        for (const [k, v] of Object.entries(pass.floats)) prog.set(k, v);
        for (const [k, v] of Object.entries(pass.arrays)) prog.setArray(k, v, 1);
        for (const [k, v] of Object.entries(pass.vec4s)) prog.setArray(k, v, 4);
        pass.textures.forEach((name, unit) => bindTexture(gl, unit, textureOf(name)));
        gl.activeTexture(gl.TEXTURE0);
        quad.draw();
        for (let unit = pass.textures.length - 1; unit >= 0; --unit) bindTexture(gl, unit, null);
        gl.activeTexture(gl.TEXTURE0);
        if (pass.name === 'tape') drops += pass.ints.DropCount;
      }

      telemetry.ticked = true;
      telemetry.seconds = plan.seconds;
      telemetry.frame = plan.frame;
      telemetry.standard = plan.standardIndex;
      telemetry.speed = plan.speed;
      telemetry.generations = plan.generations;
      telemetry.tracking = plan.tracking;
      telemetry.N = R.N;
      telemetry.Ws = R.Ws;
      telemetry.k = R.k;
      telemetry.drops = drops;
      telemetry.switchLine = plan.switchLine;
      // A uniform name the shader does not have is a dead control (glUniform
      // on -1 is a no-op); the kit counts them. One is expected: the noise
      // shader declares LineCount and never reads it, so every GLSL compiler
      // drops it and the plugin's own glUniform1i on it is a no-op too.
      telemetry.missing = Object.entries(programs).flatMap(([name, p]) => [...p.missing].filter((u) => !(name === 'noise' && u === 'LineCount')).map((u) => `${name}.${u}`));

      if (hooks.afterRender) hooks.afterRender(gl, input);
    },
  };
}

